func TestBunLockfile(t *testing.T) {
	store, root := newTestStore(t, map[string]string{
		"app/bun.lock": `{
  // Bun lockfiles use JSONC.
  "lockfileVersion": 1,
  "workspaces": {
    "": {
      "name": "app",
      "dependencies": {
        "lodash": "^4.17.21",
      },
    },
  },
  /* Packages are resolved name@version tuples. */
  "packages": {
    "lodash": ["lodash@4.17.21", "https://registry.npmjs.org/", {}, "sha512-abc"],
    "@scope/pkg": ["@scope/pkg@2.0.0", "", {}, "sha512-def"],
    "react-dom": ["react-dom@18.2.0(react@18.2.0)", "", {}, "sha512-ghi"],
  },
}
`,
	})

	assertFindings(t, store, root, "lodash 4.17.21", "app/bun.lock@4.17.21")
	assertFindings(t, store, root, "@scope/pkg 2.0.0", "app/bun.lock@2.0.0")
	assertFindings(t, store, root, "react-dom 18.2.0", "app/bun.lock@18.2.0")

	// A dependency range in the workspace section is not an installed version.
	assertFindings(t, store, root, "lodash 4.17.20")
}

func TestNpmShrinkwrapUsesPackageLockIndexer(t *testing.T) {
	store, root := newTestStore(t, map[string]string{
		"app/npm-shrinkwrap.json": `{
			"lockfileVersion": 3,
			"packages": {
				"node_modules/lodash": {"version": "4.17.20"}
			}
		}`,
	})

	assertFindings(t, store, root, "lodash 4.17.20", "app/npm-shrinkwrap.json@4.17.20")
}

func TestIndexerForRecognizesSupportedFileNames(t *testing.T) {
	for _, name := range PackageFileNames() {
		if indexerFor("project/"+name) == nil {
			t.Errorf("indexerFor(%q) = nil, want an indexer", name)
		}
	}

	if indexerFor("project/bun.lockb") != nil {
		t.Error("indexerFor(bun.lockb) is non-nil, want nil for the binary lockfile")
	}
	if indexerFor("project/package.json.backup") != nil {
		t.Error("indexerFor(package.json.backup) is non-nil, want nil")
	}
}

func TestPackageFileQueryIncludesEverySupportedFile(t *testing.T) {
	query := packageFileQuery()
	for _, name := range PackageFileNames() {
		if !strings.Contains(query, name) {
			t.Errorf("packageFileQuery() does not contain %q: %s", name, query)
		}
	}
}
