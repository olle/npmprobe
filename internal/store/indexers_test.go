func TestYarnClassicLockfile(t *testing.T) {
	store, root := newTestStore(t, map[string]string{
		"app/yarn.lock": `# yarn lockfile v1

lodash@^4.17.20, lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#abc"
  integrity sha512-abc

"@scope/pkg@^2.0.0":
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/@scope/pkg/-/pkg-2.0.0.tgz#def"

"alias@npm:real-pkg@^1.0.0":
  version "1.2.3"
  resolved "https://registry.yarnpkg.com/real-pkg/-/real-pkg-1.2.3.tgz#jkl"

app@^1.0.0:
  version "1.0.0"
  dependencies:
    lodash "^4.17.20"
`,
	})

	assertFindings(t, store, root, "lodash 4.17.21", "app/yarn.lock@4.17.21")
	assertFindings(t, store, root, "@scope/pkg 2.0.0", "app/yarn.lock@2.0.0")
	assertFindings(t, store, root, "app 1.0.0", "app/yarn.lock@1.0.0")

	// Classic npm aliases index the real package name.
	assertFindings(t, store, root, "real-pkg 1.2.3", "app/yarn.lock@1.2.3")
	assertFindings(t, store, root, "alias 1.2.3")

	// Dependency ranges are not installed versions.
	assertFindings(t, store, root, "lodash 4.17.20")
}

func TestYarnBerryLockfile(t *testing.T) {
	store, root := newTestStore(t, map[string]string{
		"app/yarn.lock": `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@scope/pkg@npm:^2.0.0":
  version: 2.1.0
  resolution: "@scope/pkg@npm:2.1.0"

"alias@npm:real-pkg@^1.0.0":
  version: 1.2.3
  resolution: "real-pkg@npm:1.2.3"

"patched@patch:patched@npm%3A1.0.0#./patches/patched.patch":
  version: 1.0.0
  resolution: "patched@patch:patched@npm%3A1.0.0#./patches/patched.patch"

"workspace-pkg@workspace:packages/workspace-pkg":
  version: 0.0.0-use.local
  resolution: "workspace-pkg@workspace:packages/workspace-pkg"
`,
	})

	assertFindings(t, store, root, "@scope/pkg 2.1.0", "app/yarn.lock@2.1.0")
	assertFindings(t, store, root, "patched 1.0.0", "app/yarn.lock@1.0.0")

	// Aliases index the real package, not the local alias.
	assertFindings(t, store, root, "real-pkg 1.2.3", "app/yarn.lock@1.2.3")
	assertFindings(t, store, root, "alias 1.2.3")

	// Metadata and local workspaces are not installed registry packages.
	assertFindings(t, store, root, "__metadata 8")
	assertFindings(t, store, root, "workspace-pkg 0.0.0-use.local")
}

